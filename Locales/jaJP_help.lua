T.tips = H .. "グループ" .. E .. [[

近くにあるノードは1つのグループとして扱われるので、ノードを1つずつ見るのではなく、グループ全体が戻ったかどうかが分かります。One shared timer per group（時間パネル）をオンにすると、グループのタイマーは1つになります。

]] .. H .. "地点を修正する（ワールドマップ）" .. E .. [[

ワールドマップのタイマーの文字またはノードのピンを右クリックすると、小さなメニューが開きます（ナビ > マーカー で有効にします）：
- この地点は空：別の人が取りました。
- グループを誰かに取られた：グループ全体が既に採取されていました。
- この地点をグループに移動：別のグループ（1、2、3… または New）に入れます。
- 短いメモを入力して Save note をクリックすると、この地点にリマインダーが付きます。地点にマウスを重ねるとメモが表示されます。メモは地点と一緒に保存されます。
ミニマップではこのメニューは開きません。ナビ > マーカー で無効にできます。

]] .. H .. "再出現時間の学習方法" .. E .. [[

ノードが戻っていて、その戦利品を取るたびに、そのノードが再出現した元の戦利品からの経過時間が保存されます（複数のノードが同時に戻っているグループでは、最新ではなく直近の戦利品のうち最も古いものが使われます）。アドオンは短すぎる間隔と長すぎる間隔を無視し、サンプルの最速の四分位から中央値（典型値）までの値を、15秒単位に丸めて時間パネルに表示します。Apply と auto-apply は中央値を使います。値を表示するには3回、自動で適用するには5回のサンプルが必要です。

]] .. H .. "地点を友達と共有する" .. E .. [[

設定 > ツール > Export my spots（または /gt export）を押すと、自分の地点が1行のテキストとして表示されます。欄をクリックして Ctrl+C を押し、友達に送ります。友達は Import spots（または /gt import）を開き、Ctrl+V で貼り付けて Import を押します。共有されるのはアイテム、ゾーン、位置だけで、タイマーや数は含まれません。すでに持っている地点はそのままで、途中で切れたテキストは半分だけ取り込まれるのではなく、拒否されます。

]] .. H .. "補助アドオン" .. E .. [[

- HereBeDragons：マップとミニマップのピンに必要です。インストールしてください。
- GatherMate2：設定 > ツール > Import GatherMate2 で、既知のノードの位置を追加します。
- TomTom：矢印とルートのウェイポイントを表示できるようにします。

]] .. H .. "問題がありますか？" .. E .. [[

- ピンが表示されない：HereBeDragons をインストールしてください。設定 > ツールで、見つかったものを確認できます。
- タイマーが始まらない：/gt debug と入力してノードから戦利品を取ると、アドオンが見ている内容を表示します。
- エラーは 設定 > ツール > Error log に一覧表示されます（クリック後、Ctrl+A、Ctrl+C でコピー）。
- 問題や他のアドオンとの競合を報告するには：設定 > ツール > Copy debug report（または /gt report）を押してテキストをコピーし、報告に貼り付けてください。
- 誤った地点やグループ：ワールドマップでそれを右クリックしてください。]]

