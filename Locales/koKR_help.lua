- 이 노드는 비어 있음: 다른 사람이 가져갔습니다.
- 그룹을 다른 사람이 가져감: 그룹 전체가 이미 채집되었습니다.
- 이 노드를 그룹으로 옮기기: 다른 그룹(1, 2, 3... 또는 New)에 넣습니다.
- 짧은 메모를 입력하고 Save note를 클릭하면 이 노드에 알림을 붙입니다. 노드에 마우스를 올리면 메모가 보입니다. 메모는 노드와 함께 저장됩니다.
미니맵에서는 이 메뉴가 열리지 않습니다. 내비 > 표시에서 끌 수 있습니다.

]] .. H .. "재생성 시간을 학습하는 방법" .. E .. [[

노드가 돌아와 전리품을 얻을 때마다, 그 노드가 재생성된 전리품 이후의 시간이 저장됩니다(여러 노드가 동시에 돌아온 그룹에서는 최근 전리품 중 가장 오래된 것을 기준으로 합니다). 애드온은 너무 짧거나 너무 긴 간격을 무시하고, 측정값의 중간값(전형값)까지의 가장 빠른 4분위 값을 15초 단위로 반올림해 시간 패널에 보여줍니다. Apply와 auto-apply는 중간값을 사용합니다. 값을 표시하려면 측정 3회, 자동 적용하려면 5회가 필요합니다.

]] .. H .. "친구와 노드 공유하기" .. E .. [[

설정 > 도구 > Export my spots(또는 /gt export)를 누르면 내 노드가 한 줄의 텍스트로 표시됩니다. 상자를 클릭하고 Ctrl+C를 누른 뒤 친구에게 보내세요. 친구는 Import spots(또는 /gt import)를 열어 Ctrl+V로 붙여넣고 Import를 클릭합니다. 아이템, 지역, 위치만 공유되며 타이머와 개수는 공유되지 않습니다. 이미 가진 노드는 그대로 두며, 전달 중에 잘린 텍스트는 절반만 가져오지 않고 거부합니다.

]] .. H .. "보조 애드온" .. E .. [[

- HereBeDragons: 지도와 미니맵 핀에 필요합니다. 설치하세요.
