- 핀이 없음: HereBeDragons를 설치하세요. 설정 > 도구에서 찾은 항목을 확인할 수 있습니다.
- 타이머가 시작되지 않음: /gt debug를 입력하고 노드에서 전리품을 얻으면, 애드온이 무엇을 보는지 출력합니다.
- 오류는 설정 > 도구 > Error log에 나열됩니다(클릭 후 Ctrl+A, Ctrl+C로 복사).
- 문제나 다른 애드온과의 충돌을 보고하려면: 설정 > 도구 > Copy debug report(또는 /gt report)를 눌러 텍스트를 복사하고 보고서에 붙여넣으세요.
- 잘못된 노드나 그룹: 세계 지도에서 그 노드를 오른쪽 클릭하세요.]]

