T.tips = H .. "Группы" .. E .. [[

Близкие точки считаются одной группой, поэтому вы видите, когда вернулась вся группа, а не каждая точка по отдельности. С One shared timer per group (панель Время) у группы один таймер.

]] .. H .. "Исправить точку (карта мира)" .. E .. [[

Правый клик по тексту таймера или по метке точки на карте мира открывает небольшое меню (включается в Метки > Путь):
- Эта точка пуста: её забрал кто-то другой.
- Группа забрана кем-то: вся группа уже была собрана.
- Переместить эту точку в группу: поставить её в другую группу (1, 2, 3... или New).
- Введите короткую заметку и нажмите Save note, чтобы прикрепить напоминание к точке. Наведите курсор на точку, чтобы увидеть заметку. Заметки сохраняются вместе с точкой.
Миникарта это меню никогда не открывает. Его можно отключить в Путь > Метки.

]] .. H .. "Как изучаются времена появления" .. E .. [[

Каждый раз, когда точка возвращается и вы забираете её добычу, сохраняется время от добычи, для которой она является повторным появлением (в группе, где несколько точек вернулись одновременно, берётся самая старая из недавних добыч, а не самая новая). Аддон игнорирует слишком короткие и слишком длинные промежутки, затем показывает в Время значение от самой быстрой четверти до медианы (типичного значения) ваших замеров, округлённое до 15 секунд. Apply и auto-apply используют медиану. Для показа значения нужно 3 замера, для автоматического применения — 5.

]] .. H .. "Делиться точками с друзьями" .. E .. [[

Опции > Утил. > Export my spots (или /gt export) показывает ваши точки одной строкой текста. Нажмите в поле, нажмите Ctrl+C и отправьте другу. Друг использует Import spots (или /gt import), вставляет текст через Ctrl+V и нажимает Import. Передаются только предмет, зона и позиция, без таймеров и счётчиков. Точки, которые у него уже есть, не меняются, а текст, обрезанный по дороге, отклоняется, а не импортируется наполовину.

]] .. H .. "Вспомогательные аддоны" .. E .. [[

- HereBeDragons: нужен для меток на карте и миникарте. Установите его.
- GatherMate2: Опции > Утил. > Import GatherMate2 добавляет известные ему места точек.
- TomTom: позволяет показывать стрелку и путевые точки маршрутов.

]] .. H .. "Что-то не так?" .. E .. [[

- Нет меток: установите HereBeDragons. Опции > Утил. показывает, что найдено.
- Таймеры не запускаются: введите /gt debug и заберите добычу с точки; аддон выведет, что он видит.
- Ошибки перечислены в Опции > Утил. > Error log (кликните, Ctrl+A, Ctrl+C для копирования).
- Чтобы сообщить о проблеме или конфликте с другим аддоном: Опции > Утил. > Copy debug report (или /gt report), скопируйте текст и вставьте в отчёт.
- Неверная точка или группа: правый клик по ней на карте мира.]]

